export const RADICAL_TYPE: Record<number, TypeId> = {};
for (const [type, nums] of Object.entries(TABLE) as [TypeId, number[]][]) {
  for (const n of nums) {
    if (RADICAL_TYPE[n]) throw new Error(`radical ${n} mapped twice`);
    RADICAL_TYPE[n] = type;
  }
}
for (let n = 1; n <= 214; n++) {
  if (!RADICAL_TYPE[n]) throw new Error(`radical ${n} has no type`);
}
